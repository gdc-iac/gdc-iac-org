# Generates a deterministic YAML manifest mapping each Helm chart in charts/*
# to its <chart_name_with_underscores>_chart_version variable for Mode 2 OCI
# consumption in foundations/bases/environments/<env>/chart-versions.yaml.
#
# Usage:
#   ./scripts/generate-chart-versions.sh [--output <file>]

set -euo pipefail

REPO_ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUTPUT_FILE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--output)
      OUTPUT_FILE="$2"
      shift 2
      ;;
    -h|--help)
      sed -n '16,21p' "${BASH_SOURCE[0]}"
      exit 0
      ;;
    *)
      echo "Error: unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

emit_manifest() {
  cat <<'HEADER'
# Copyright 2026 Google LLC
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#     http://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.

---
# ==============================================================================
# GDC IaC Helm Chart Version Manifest (Mode 2: OCI Registry Consumption)
#
# Generated by scripts/generate-chart-versions.sh from charts/*/Chart.yaml.
# Keep static OCI URLs in foundations/bases/environments/<env>/charts.yaml and
# copy this manifest into foundations/bases/environments/<env>/chart-versions.yaml
# so Helmfile automatically pins every chart to the exact release bundle version.
# ==============================================================================

HEADER

  local chart_yaml chart_dir chart_name chart_version var_name
  while IFS= read -r chart_yaml; do
    [[ -n "${chart_yaml}" ]] || continue
    chart_dir="$(basename "$(dirname "${chart_yaml}")")"
    chart_name="$(awk '/^name:[[:space:]]*/ { sub(/^name:[[:space:]]*/, ""); sub(/[[:space:]]*#.*/, ""); gsub(/["'\''[:space:]]/, ""); print; exit }' "${chart_yaml}")"
    [[ -n "${chart_name}" ]] || chart_name="${chart_dir}"
    chart_version="$(awk '/^version:[[:space:]]*/ { sub(/^version:[[:space:]]*/, ""); sub(/[[:space:]]*#.*/, ""); gsub(/["'\''[:space:]]/, ""); print; exit }' "${chart_yaml}")"
    if [[ -z "${chart_version}" ]]; then
      echo "Error: missing version in ${chart_yaml}" >&2
      exit 1
    fi
    var_name="${chart_name//-/_}_chart_version"
    printf '%s: "%s"\n' "${var_name}" "${chart_version}"
  done < <(find "${REPO_ROOT}/charts" -mindepth 2 -maxdepth 2 -name "Chart.yaml" | LC_ALL=C sort)
}

if [[ -n "${OUTPUT_FILE}" ]]; then
  mkdir -p "$(dirname "${OUTPUT_FILE}")"
  emit_manifest > "${OUTPUT_FILE}"
else
  emit_manifest
fi
